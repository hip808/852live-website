export function pickLanguage(stored, navLang) {
  if (stored === 'en' || stored === 'zh' || stored === 'zht') return stored;
  const n = String(navLang || '').toLowerCase();
  if (!n.startsWith('zh')) return 'en';
  return /^zh-(tw|hk|mo|hant)/.test(n) ? 'zht' : 'zh';
}

